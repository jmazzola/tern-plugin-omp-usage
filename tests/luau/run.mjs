#!/usr/bin/env node
// Runs the plugin's Luau tests (tests/luau/*.spec.luau) with the Luau CLI, `luau`, from
// https://github.com/luau-lang/luau/releases (luau-windows.zip, luau-ubuntu.zip, luau-macos.zip).
// Point LUAU at the executable, or put it on PATH. Usage: node tests/luau/run.mjs [filter]
//
// The Luau CLI can't read files, so this writes the plugin's .luau files as strings into `sources.luau` in a temp
// folder, beside a copy of this folder's .luau files, and runs `run.luau` there (see harness.luau).
import { execFileSync, spawnSync } from "node:child_process";
import { copyFileSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..");

// 0.7.10, the last release before the cache was compacted.
const RELEASED = "24208a0";

function findLuau() {
  if (process.env.LUAU) return process.env.LUAU;
  const finder = process.platform === "win32" ? "where" : "which";
  for (const name of process.platform === "win32" ? ["luau.exe", "luau"] : ["luau"]) {
    try {
      const found = execFileSync(finder, [name], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] })
        .split(/\r?\n/)
        .find(Boolean);
      if (found) return found.trim();
    } catch {
      // not on PATH under that name
    }
  }
  return null;
}

// `text` as a Luau long string: the shortest `[==[` level its own text doesn't close, and a newline first (Luau
// drops the one right after the opening bracket), so the file's lines keep their numbers.
function longString(text) {
  let level = 0;
  while (text.includes("]" + "=".repeat(level) + "]")) level += 1;
  const eq = "=".repeat(level);
  return `[${eq}[\n${text}]${eq}]`;
}

const luau = findLuau();
if (!luau) {
  console.error(
    "No Luau CLI found. Download luau from https://github.com/luau-lang/luau/releases and put it on PATH, " +
      "or set LUAU to its path."
  );
  process.exit(2);
}

const work = mkdtempSync(join(tmpdir(), "ompu-luau-"));
try {
  const plugin = readdirSync(root).filter((name) => name.endsWith(".luau"));
  const entries = plugin.map((name) => `\t[${JSON.stringify(name)}] = ${longString(readFileSync(join(root, name), "utf8"))},`);
  // The last release's reader (0.7.10), for what copies that haven't updated make of today's cache: its files from
  // git, when git and that commit are there (the tests that need them skip otherwise).
  for (const name of ["data.luau", "details.luau"]) {
    try {
      const text = execFileSync("git", ["show", `${RELEASED}:${name}`], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
      entries.push(`\t[${JSON.stringify(`v0.7.10/${name}`)}] = ${longString(text)},`);
    } catch {
      // no git, or a clone without that commit
    }
  }
  writeFileSync(join(work, "sources.luau"), `-- generated by tests/luau/run.mjs\nreturn {\n${entries.join("\n")}\n}\n`);
  const own = readdirSync(here).filter((name) => name.endsWith(".luau"));
  for (const name of own) {
    copyFileSync(join(here, name), join(work, name));
  }
  // Each spec returns true: the Luau CLI's `require` hands back a file's compile error as its value instead of
  // raising it, so a spec that doesn't load must fail the run here rather than be skipped.
  const specs = own
    .filter((name) => name.endsWith(".spec.luau"))
    .map((name) => {
      const module = `./${name.slice(0, -5)}`;
      return `do local r = require("${module}") if r ~= true then error("${name} didn't load: " .. tostring(r), 0) end end`;
    });
  writeFileSync(join(work, "specs.luau"), `-- generated by tests/luau/run.mjs\n${specs.join("\n")}\nreturn nil\n`);
  const filter = process.argv[2] ?? "";
  const result = spawnSync(luau, ["run.luau", "-a", filter], { cwd: work, stdio: "inherit" });
  if (result.error) {
    console.error(`Couldn't run ${luau}: ${result.error.message}`);
    process.exitCode = 2;
  } else {
    process.exitCode = result.status ?? 1;
  }
} finally {
  if (!process.env.KEEP_LUAU_WORK) rmSync(work, { recursive: true, force: true });
  else console.error(`kept ${work}`);
}
